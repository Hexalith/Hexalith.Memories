namespace Hexalith.Memories.Mcp.Tests;

using Microsoft.Extensions.Logging;

/// <summary>Captures formatted tool logs during the logger call.</summary>
internal sealed class ToolFailureTestLogger : ILogger<McpToolExecutor>
{
    /// <summary>Gets the formatted log entries.</summary>
    public List<(LogLevel Level, string Message, Exception? Exception)> Entries { get; } = [];

    /// <inheritdoc />
    public IDisposable? BeginScope<TState>(TState state)
        where TState : notnull => null;

    /// <inheritdoc />
    public bool IsEnabled(LogLevel logLevel) => true;

    /// <inheritdoc />
    public void Log<TState>(
        LogLevel logLevel, EventId eventId, TState state, Exception? exception, Func<TState, Exception?, string> formatter)
        => Entries.Add((logLevel, formatter(state, exception), exception));
}
